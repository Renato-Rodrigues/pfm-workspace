#' One registry row, or stop with a useful message
figureEntry <- function(id) {
  reg <- figureRegistry()
  hit <- reg[reg$id == id, , drop = FALSE]
  if (!nrow(hit)) {
    stop("unknown figure '", id, "'. Known: ", paste(reg$id, collapse = ", "), call. = FALSE)
  }
  as.list(hit[1, ])
}
