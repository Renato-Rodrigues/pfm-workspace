# The figure registry — the single source of truth for what figures exist.
#
# One row per figure, so nothing about a figure can drift between the paper, the deck,
# the poster and the reports. If a figure is
# not in here it does not exist; if a field is empty the figure is not finished.
#
# Every consumer pulls from this table:
#   paper        -> caption, and the rendered file
#   presentation -> shows / reads, and the rendered file at slide size
#   poster       -> the rendered file at poster size
#   reports      -> the whole explainer

#' The canonical figure registry
#'
#' @param consumers Optional character vector; keep only figures consumed by at least one of
#'   these (\code{"paper"}, \code{"slides"}, \code{"poster"}, \code{"report"}).
#' @param status Optional character vector; keep only figures with these statuses
#'   (\code{"built"}, \code{"planned"}).
#' @return A data.frame, one row per figure.
